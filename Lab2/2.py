    def _refresh_visual_panels(self):
        alg = self.gl.algorithm
        zb = alg.get_zbuffer_row()
        if zb is not None and zb.size > 0:
            finite = zb[np.isfinite(zb)]
            if finite.size > 0:
                zmin = float(finite.min()); zmax = float(finite.max())
                step = max(1, len(zb) // 40)
                vals = []
                for i in range(0, len(zb), step):
                    if np.isfinite(zb[i]):
                        vals.append(f"{zb[i]:.1f}")
                    else:
                        vals.append("·")
                self.zb_label.setText(
                    f"min={zmin:.2f}  max={zmax:.2f}  активных пикселов: {finite.size}\n"
                    f"[{' '.join(vals[:40])}]")
            else:
                self.zb_label.setText("(нет активных пикселов на текущей строке)")
        else:
            self.zb_label.setText("—")

        edges = alg.get_active_edges_info()
        if not edges:
            self.ael_label.setText("(пуст)")
        else:
            lines = []
            for e in edges[:40]:
                zs = f"{e['z']:.2f}" if e['z'] is not None else "—"
                lines.append(f"P{e['pid']} {e['side']}  x={e['x_log']:+.2f}  z={zs}")
            if len(edges) > 40:
                lines.append(f"... ещё {len(edges) - 40}")
            self.ael_label.setText("\n".join(lines))

    def on_instant_clicked(self):
        if self.gl.algorithm.finished:
            self.gl.reset_algorithm()
        self.gl.start_instant()

    def on_progressive_clicked(self):
        if self.gl.algorithm.finished:
            self.gl.reset_algorithm()
        self.gl.start_progressive()

    def on_stop_clicked(self):
        self.gl.stop_progressive()

    def on_step_clicked(self):
        if self.gl.algorithm.running:
            return
        if self.gl.algorithm.finished:
            self.gl.reset_algorithm()
        # Скрыть оси и включить пошаговый режим, чтобы показывалась визуализация
        self.gl.show_axes = False
        self.gl.step_mode = True
        self.gl.algorithm.on_tick()
        if not self.gl.algorithm.finished:
            self.gl.algorithm.paused = True
        self.gl.update()
        self._refresh_visual_panels()

    def on_reset_clicked(self):
        self.gl.reset_algorithm()

