# Создаёт демонстрационную сцену: прямоугольник и треугольник,
# которые протыкают друг друга. Прямоугольник стоит вертикально на
# глубине Z=1, а треугольник наклонён и пересекает его
def generate_demo_scene():
    scene = [] # здесь будем собирать все полигоны сцены
    # Прямоугольник. 4 вершины в однородных координатах (x, y, z, 1).
    # Все они лежат в плоскости Z = 1 — прямоугольник стоит вертикально
    rect_verts = [(1.0, 0.5, 1.0, 1.0), (1.0, 2.5, 1.0, 1.0),
                  (2.5, 2.5, 1.0, 1.0), (2.5, 0.5, 1.0, 1.0)]
    scene.append({'id': 0, 'verts': np.array(rect_verts, dtype=float),
                  'color': QtGui.QColor( 60, 175, 120)})   # изумрудный прямоугольник
    # Треугольник. 3 вершины на разной глубине Z —
    # значит, он наклонён и не параллелен экрану.
    # Именно поэтому в одной части экрана он ближе прямоугольника,
    # а в другой — дальше. Так и получается «протыкание»
    tri_verts = [(1.5, 1.5, 1.5, 1.0), (2.5, 2.5, 0.5, 1.0), (3.0, 1.0, 0.5, 1.0)]
    scene.append({'id': 1, 'verts': np.array(tri_verts, dtype=float),
                  'color': QtGui.QColor(225,  95,  95)})   # коралловый треугольник
    return scene # список словарей, каждый описывает один полигон

# Создаёт случайную сцену из нескольких многоугольников
# (по умолчанию 6 штук)
def generate_random_scene(num_polys=6):
    scene = [] # список полигонов
    # Для каждого номера pid от 0 до num_polys-1 создаём один полигон
    for pid in range(num_polys):
        # Центр полигона — случайная точка в небольшой области вокруг начала координат.
        # По X и Y разброс чуть шире, по Z поменьше, чтобы сцена не растянулась вглубь.
        # Значения по Z взяты так, чтобы полигоны оказались перед камерой (не за ней)
        center = (random.uniform(-1.5, 1.5), random.uniform(-1.0, 1.0), random.uniform(-0.8, 1.2))
        # Нормаль — вектор, задающий ориентацию плоскости полигона в пространстве
        normal = (random.uniform(-0.8, 0.8), random.uniform(-0.8, 0.8), random.uniform(-0.6, 0.6) + 0.2)
        # Генерируем сам полигон через make_polygon:
        # - radius случайный от 0.5 до 1.4 (одни полигоны мелкие, другие крупные)
        # - n_verts — от 3 до 6 вершин
        verts = make_polygon(center, normal, random.uniform(0.5, 1.4), random.randint(3, 6))
        # Цвет берём из палитры по кругу. Умножение на 3 даёт «прыжки» через
        # 3 позиции, чтобы соседние полигоны получались разного цвета
        color = PALETTE[(pid * 3) % len(PALETTE)]
        # Кладём готовый полигон в сцену
        scene.append({'id': pid, 'verts': np.array(verts, dtype=float), 'color': color})
    return scene

# Строит уравнение плоскости по трём точкам: A*x + B*y + C*z + D = 0.
# Коэффициенты A, B, C — это нормаль к плоскости (вектор, перпендикулярный ей),
# а D подбирается так, чтобы плоскость проходила через заданные точки
def plane_from_points(p0, p1, p2):
    # Берём две стороны будущего параллелограмма, построенного на точках
    v1 = p1 - p0; v2 = p2 - p0
    # Нормаль к плоскости = векторное произведение этих двух векторов.
    # Она перпендикулярна и v1, и v2, а значит, перпендикулярна плоскости
    n = np.cross(v1, v2)
    a, b, c = n # это коэффициенты A, B, C уравнения плоскости
    # Коэффициент D находим, подставив одну из точек (например, p0) в уравнение.
    # Из A*x + B*y + C*z + D = 0 выражаем D = -(A*x + B*y + C*z)
    d = -(a * p0[0] + b * p0[1] + c * p0[2])
    # Возвращаем кортеж из 4 чисел
    return float(a), float(b), float(c), float(d)


# Это основной класс, который реализует алгоритм удаления невидимых
# поверхностей методом построчного сканирования с z-буфером.
# Идея алгоритма:
#   1. Обрабатываем изображение строка за строкой (сверху вниз).
#   2. Для каждой строки находим, какие полигоны её пересекают.
#   3. Для каждого пиксела строки считаем глубину z полигонов,
#      которые в нём видны, и оставляем только самый близкий.
# В итоге каждый пиксел получает цвет того полигона, который ближе
# всех к камере именно в этом пикселе. Так корректно рисуются
# даже протыкающие друг друга полигоны
class ZBufferScanline(QtCore.QObject):
    # Сигнал: сообщить, когда нужно перерисовать окно
    # (например, после обработки очередной строки)
    updated = QtCore.pyqtSignal()
    # Сигнал: сообщить, что строка с номером N закончена
    # (аргумент — номер строки)
    rowCompleted = QtCore.pyqtSignal(int)

    # Конструктор класса ZBufferScanline.
    # Параметры:
    # scene — список полигонов сцены (словари с 'id', 'verts', 'color')
    # focal — фокусное расстояние камеры (для перспективной проекции)
    # width, height — размеры экрана в пикселях (ширина и высота)
    # scale_screen — коэффициент перевода логических координат в пиксели
    # camera_pos — положение камеры в мировых координатах (x, y, z)
    # camera_target — точка, на которую смотрит камера (x, y, z)
    # camera_up — вектор «вверх» камеры (0, 1, 0)
    def __init__(self, scene, focal, width, height, scale_screen,
                 camera_pos, camera_target, camera_up):
        # Вызов конструктора родительского класса QObject
        super().__init__()
        self.scene = scene
        self.focal = float(focal)
        self.W = int(width); self.H = int(height)
        self.scale_screen = scale_screen
        # Центр экрана в пикселях — точка, куда попадает логическое (0, 0)
        self.cx = self.W / 2.0; self.cy = self.H / 2.0
        self.camera_pos = np.array(camera_pos, dtype=float)
        self.camera_target = np.array(camera_target, dtype=float)
        self.camera_up = np.array(camera_up, dtype=float)
        # Кэши, которые заполняются в _prepare_projection():
        # projected — для каждого полигона: список спроецированных вершин в виде (x_log, y_log, z_cam)
        # cam_coords  — координаты вершин в системе камеры (без проекции),
        # нужны для построения уравнения плоскости
        # poly_planes — коэффициенты (a, b, c, d) уравнения плоскости каждого полигона
        self.projected = {}
        self.cam_coords = {}
        self.poly_planes = {}
        self._prepare_projection()

        # Номер строки, которую сейчас обрабатываем.
        # 0 — самая верхняя строка экрана, дальше идём вниз
        self.cur_scanline = 0

        # Флаг: сейчас работает таймер (прогрессивный режим) или нет
        self.running = False

        # Таймер для прогрессивного режима.
        # Каждые 20 мс вызывает self.on_tick — то есть обрабатывает одну строку
        self.timer = QtCore.QTimer(); self.timer.timeout.connect(self.on_tick)
        self.timer.setInterval(20)

        # Данные по текущей обрабатываемой строке:
        # active_edges — список активных рёбер (для отладочной панели AEL).
        # Это рёбра полигонов, которые пересекают текущую строку
        self.active_edges = []

        # active_pairs — пары "левое ребро — правое ребро" одного полигона.
        # Каждая пара задаёт горизонтальный отрезок, который полигон
        # занимает на этой строке. По этим парам заливаем пиксели
        self.active_pairs = []

        # current_intersections — точки пересечения рёбер со строкой
        self.current_intersections = []

        # active_polygons — множество полигонов, которые сейчас пересекают строку
        self.active_polygons = set()

        # Буферы. Пока пустые — заполнит _reallocate_buffers() ниже
        self.scanline_zbuffer = None # z-буфер для одной строки: глубина пикселов
        self.scanline_fbuffer = None # для каждого пиксела текущей строки хранит id полигона, который в нём видно
        self.frame_pid = None # для каждого пиксела всего экрана хранит id полигона, который в нём видно.
        self.frame_z = None # для каждого пиксела хранит глубину видимого полигона
        
        # Создаём все буферы под текущие размеры W и H
        self._reallocate_buffers()

        # Флаг: алгоритм завершён (все строки обработаны)
        self.finished = False
        # Флаг: алгоритм на паузе 
        self.paused = False

    # Создаёт (или пересоздаёт) все буферы под текущие размеры W и H.
    # Вызывается в трёх случаях:
    # 1) при инициализации сцены — чтобы сразу создать буферы нужного размера,
    # 2) при смене разрешения окна — чтобы массивы подогнались под новый размер,
    # 3) при сбросе алгоритма — чтобы очистить буферы от старых данных
    def _reallocate_buffers(self):
        # Ещё раз приводим размеры к int на всякий случай.
        # Если снаружи пришли float или другие числа — обрежем до целых,
        # иначе np.full() может выдать ошибку
        self.W = int(self.W); self.H = int(self.H)

        # Пересчитываем координаты центра экрана.
        # Делаем это здесь, а не где-то отдельно, потому что центр
        # напрямую зависит от W и H — если они поменялись, центр тоже меняется
        self.cx = self.W / 2.0; self.cy = self.H / 2.0

        # z-буфер для одной строки — массив длиной W (по количеству пикселов
        # в строке). Изначально все значения = +бесконечность
        self.scanline_zbuffer = np.full((self.W,), np.inf, dtype=float)
        # Буфер цвета для одной строки (id полигона) — массив длиной W, заполняем значением -1
        self.scanline_fbuffer = np.full((self.W,), -1, dtype=int)

        # Итоговый буфер всего кадра: H * W пикселей
        self.frame_pid = np.full((self.H, self.W), -1, dtype=int)

        # Итоговый буфер глубин всего кадра: тоже H * W
        self.frame_z = np.full((self.H, self.W), np.inf, dtype=float)

    # Сменить разрешение экрана (например, при измененении размера окна приложения)
    # Буферы пересоздаются под новый размер, а алгоритм сбрасывается в начальное состояние

    # Параметры:
    #   width  — новая ширина экрана в пикселях
    #   height — новая высота экрана в пикселях
    def resize(self, width, height):
        # Приводим размеры к int
        width = int(width); height = int(height)
        # Если размеры те же самые — ничего делать не надо
        if width == self.W and height == self.H and self.frame_pid is not None:
            return
        # Сохраняем новые размеры в поля класса
        self.W = width; self.H = height
        # Пересоздаём все четыре буфера под новый размер
        self._reallocate_buffers()
         # Сбрасываем алгоритм: обнуляем буферы, пересчитываем проекции, ставим указатель на строку 0
        self.reset()

    # Предварительные расчёты для всей сцены:
    #   1) проецируем все вершины полигонов на экран,
    #   2) сохраняем координаты вершин в системе камеры,
    #   3) для каждого полигона строим уравнение его плоскости.
    # Функция вызывается один раз при создании сцены и всякий раз,
    # когда меняется камера или сцена — то есть когда все эти данные
    # нужно пересчитать заново
    def _prepare_projection(self):
        # Чистим старые данные — иначе останутся значения от прошлой камеры
        self.projected.clear(); self.cam_coords.clear(); self.poly_planes.clear()
        # Проходим по всем полигонам сцены
        for p in self.scene:
            pid = p['id'] # уникальный номер полигона
            # Проецируем вершины этого полигона на экран.
            # Функция возвращает два результата:
            # proj — список из (x_log, y_log, z_cam) или None (вершина за камерой)
            # pts_cam — те же точки, но без проекции, в системе координат камеры
            proj, pts_cam = project_with_camera_and_depth(
                p['verts'], self.camera_pos, self.camera_target,
                self.camera_up, self.focal)
            # Сохраняем проекции вершин — они понадобятся при построчном
            # поиске пересечений рёбер со строкой
            self.projected[pid] = proj
            # Сохраняем координаты вершин в системе камеры.
            # Из каждого вектора берём только первые три компоненты (x, y, z),
            # а четвёртое w отбрасываем — оно нам дальше не нужно
            self.cam_coords[pid] = np.array([pc[:3] for pc in pts_cam], dtype=float)
            found = False
            # Через три точки, не лежащие на одной прямой, проходит
            # ровно одна плоскость. Но мы не знаем заранее, какие вершины
            # подойдут (какие из них коллинеарны), поэтому перебираем
            # все тройки подряд, пока не найдём подходящую
            cc = self.cam_coords[pid]; n = len(cc)  # список координат вершин (x, y, z), сколько вершин у полигона
            # Тройной цикл перебирает все комбинации трёх вершин без повторений:
            # i < j < k — так мы каждую тройку берём ровно один раз
            for i in range(n):
                for j in range(i + 1, n):
                    for k in range(j + 1, n):
                        p0, p1, p2 = cc[i], cc[j], cc[k]
                        # Проверяем, не лежат ли три точки на одной прямой.
                        # Строим два вектора: (p1 - p0) и (p2 - p0).
                        # Их векторное произведение даёт нормаль к плоскости,
                        # построенной на этих трёх точках. Если длина этой
                        # нормали больше eps — точки не на одной прямой,
                        # плоскость построить можно
                        if np.linalg.norm(np.cross(p1 - p0, p2 - p0)) > 1e-8:
                            # Считаем коэффициенты (a, b, c, d) уравнения плоскости
                            # A*x + B*y + C*z + D = 0 и сохраняем их
                            self.poly_planes[pid] = plane_from_points(p0, p1, p2)
                            found = True; break
                        # (если точки на одной прямой — пробуем следующую тройку)
                    if found: break
                if found: break
            # Если ни одна тройка вершин не подошла (например, полигон
            # вырожденный — все точки лежат на одной прямой),
            # сохраняем None. Для такого полигона уравнение плоскости
            # построить нельзя, и глубина в его точках будет не определена
            if not found:
                self.poly_planes[pid] = None

    # Сменить положение камеры.
    # После этого надо пересчитать проекции всех вершин и уравнения плоскостей —
    # потому что они зависят от того, откуда мы смотрим на сцену
    def set_camera(self, camera_pos):
        # Сохраняем новое положение камеры
        self.camera_pos = np.array(camera_pos, dtype=float)
        # Пересчитываем проекции и плоскости полигонов под новую камеру
        self._prepare_projection()

    # Полный сброс: возвращаем алгоритм в самое начальное состояние,
    # как будто мы только что запустили программу
    def reset(self):
        # Начинаем с самой верхней строки
        self.cur_scanline = 0
        # Чистим данные по текущей строке (активные рёбра, пары, точки пересечений, список активных полигонов)
        self.active_edges.clear(); self.active_pairs.clear()
        self.current_intersections.clear(); self.active_polygons.clear()
        # Пересоздаём буферы
        self._reallocate_buffers()
        # Пересчитываем проекции вершин и уравнения плоскостей —
        # на случай, если сцена или камера поменялись
        self._prepare_projection()
        # Снимаем флаги состояния
        self.finished = False
        self.paused = False
        # Сообщаем окну, что надо перерисоваться
        self.updated.emit()

    # Запуск прогрессивного режима.
    # Если предыдущий прогон уже завершён — сначала сбрасываем всё,
    # чтобы начать заново. Потом включаем таймер, который будет
    # вызывать on_tick каждые 20 мс (одна строка за тик)
    def start(self):
        # Если алгоритм был завершён ранее — начинаем заново
        if self.finished:
            self.reset()
        # Если таймер ещё не запущен — включаем
        if not self.running:
            self.running = True
            self.paused = False
            self.timer.start()

    # Пауза прогрессивного режима: останавливаем таймер, но НЕ сбрасываем
    # ничего. Уже отрисованные строки остаются, буферы не чистятся.
    # При следующем start() алгоритм продолжит с той же строки, где остановился
    def pause(self):
        if self.running:
            self.running = False
            self.paused = True
            self.timer.stop()

    # Обработчик таймера: одна строка за тик (каждые 20 мс)
    def on_tick(self):
        # Если вышли за пределы экрана — все строки обработаны
        # cur_scanline — номер текущей строки. H — высота экрана.
        # Вторая проверка (frame_pid.shape[0]) — на случай, если размер окна
        # поменялся «на ходу» и H уже не совпадает с фактическим размером массива
        if self.cur_scanline >= self.H or self.cur_scanline >= self.frame_pid.shape[0]:
            # Ставим флаг «завершено» 
            if not self.finished:
                self.finished = True
            self.running = False
            self.timer.stop()
            # Просим окно перерисоваться
            self.updated.emit()
            return
        # Метка времени начала обработки. Передаётся в _process_scanline
        start = time.time()
        # Запускаем обработку строки с номером cur_scanline
        self._process_scanline(self.cur_scanline, start)
        # Сообщаем: строка готова. GLWidget по этому сигналу копирует её
        # из frame_pid в итоговое изображение frame_image
        self.rowCompleted.emit(self.cur_scanline)
        # Просим окно перерисоваться
        self.updated.emit()
        # Переходим к следующей строке (вниз по экрану)
        self.cur_scanline += 1

    # Мгновенный режим: обработать все строки за один вызов, без таймера
    def run_full(self):
        # Сбрасываем всё в начальное состояние (буферы, счётчики, проекции)
        self.reset()
        # Запоминаем H на старте: если размер окна изменится в процессе,
        # цикл всё равно пройдёт ровно столько итераций, сколько нужно
        H_snapshot = self.H
        # Идём по всем строкам сверху вниз
        for y in range(H_snapshot):
            # Защита от выхода за пределы массива
            if y >= self.frame_pid.shape[0]:
                break
            # Обрабатываем строку y
            start = time.time()
            self._process_scanline(y, start)
            # Сообщаем о готовности строки
            self.rowCompleted.emit(y)
        # Всё готово — ставим флаги и просим перерисовку
        self.finished = True
        self.cur_scanline = self.H
        self.updated.emit()

    # Считает глубину z точки на плоскости полигона pid
    # в логических координатах (x_log, y_log).
    # Формула выведена из уравнения плоскости A·x + B·y + C·z + D = 0
    # и связи логических координат с мировыми:
    # x = x_log · z / f,   y = y_log · z / f
    # Отсюда:
    # z = -D·f / (A·x_log + B·y_log + C·f)
    # Возвращает число (глубину) или None, если глубину посчитать нельзя
    def z_at(self, pid, x_log, y_log):
        # Берём уравнение плоскости для этого полигона.
        # Если полигон вырожденный (плоскость не построена) — сразу None
        plane = self.poly_planes.get(pid, None)
        if plane is None:
            return None
        # Распаковываем коэффициенты уравнения плоскости
        a, b, c, d = plane
        # Знаменатель формулы: A·x_log + B·y_log + C·f.
        # Если он равен нулю — плоскость параллельна лучу зрения, глубину определить нельзя
        denom = a * x_log + b * y_log + c * self.focal
        if abs(denom) < 1e-12:
            return None
        # Считаем промежуточный коэффициент s = -D / знаменатель.
        # По сути это масштаб вдоль луча до точки пересечения с плоскостью
        s = -d / denom
        # Если s <= 0 — точка лежит позади камеры, её не видно
        if s <= 0:
            return None
        # Итоговая глубина
        return float(s * self.focal)

    # Основной метод: обработка одной строки с номером y_px.
    # Здесь реализована суть алгоритма z-буфера:
    # 1. Ищем, какие полигоны пересекают строку.
    # 2. Для каждого полигона находим пары "левое ребро — правое ребро".
    # 3. Между парой рёбер для каждого пиксела считаем глубину z
    # и оставляем только тот полигон, который ближе всех к камере.
    # Параметры:
    # y_px       — номер строки (0 = верхняя, H-1 = нижняя)
    # start_time — метка времени начала 
    def _process_scanline(self, y_px, start_time):
        # Защита от выхода за границы экрана
        if y_px < 0 or y_px >= self.H:
            return
        # Вторая защита — на случай, если массив буфера меньше ожидаемого
        if y_px >= self.frame_pid.shape[0]:
            return
        
        # 1) Обнуляем данные по текущей строке 
        # Чистим списки активных рёбер, пар, пересечений и множество полигонов.
        # Это данные ПРЕДЫДУЩЕЙ строки — для новой они не подходят
        self.active_edges.clear()
        self.active_pairs.clear()
        self.current_intersections.clear()
        self.active_polygons.clear()
        self.scanline_zbuffer.fill(np.inf)
        self.scanline_fbuffer.fill(-1)

        # Переводим номер пиксельной строки в логическую координату Y.
        # 1) y_px + 0.5 — берём центр пиксельной строки
        # 2) cy − (...) — переворачиваем ось: на экране Y идёт вниз, в логике — вверх
        # 3) / scale_screen — переводим пиксели в логические единицы
        # (scale_screen = сколько пикселей в одной логической единице, обычно min(W, H) * 0.5)
        y_log = (self.cy - (y_px + 0.5)) / self.scale_screen

        # 2) Ищем пересечения строки с рёбрами всех полигонов
        # per_poly_xs: словарь вида pid -> список пар (x_log, x_px) точек пересечения 
        # в логических и пиксельных координатах
        # Для каждого полигона соберём все точки, где его рёбра пересекают текущую строку
        per_poly_xs = {}
        for p in self.scene:
            pid = p['id']
            # Достаём спроецированные вершины этого полигона.
            # Если полигон не проецировался — пропускаем
            proj = self.projected.get(pid)
            if proj is None:
                continue
            # сколько вершин у полигона
            n = len(proj)
            # здесь будут пересечения рёбер этого полигона
            xs = []
            # Перебираем рёбра
            # (i + 1) % n — «зацикливает» индекс: после последней вершины
            # берётся первая, чтобы последнее ребро замкнуло контур полигона
            for i in range(n):
                p1 = proj[i]; p2 = proj[(i + 1) % n]
                # Если какая-то из вершин за камерой (None) — ребро пропускаем
                if p1 is None or p2 is None:
                    continue
                x1, y1, z1 = p1; x2, y2, z2 = p2
                # Проверяем: попадает ли y_log между y1 и y2 (в любом порядке).
                # Это значит, что ребро пересекает нашу горизонтальную строку
                if (y1 <= y_log <= y2) or (y2 <= y_log <= y1):
                    # Если ребро строго горизонтальное — параметр t посчитать нельзя
                    if abs(y2 - y1) < 1e-12:
                        continue
                    # Параметр t: где именно на ребре мы находимся.
                    # t = 0 в точке p1, t = 1 в точке p2
                    # Формула получается из условия Y(t) = y_log, где Y(t) = y1 + t*(y2 - y1):
                    # y_log = y1 + t*(y2 - y1) -> t = (y_log - y1) / (y2 - y1)
                    t = (y_log - y1) / (y2 - y1)
                    # Находим X точки пересечения со строкой
                    x_int = x1 + t * (x2 - x1)
                    # Переводим логическую X в пиксельную:
                    # добавляем центр экрана и умножаем на масштаб
                    x_px = self.cx + x_int * self.scale_screen
                    # Сохраняем оба значения в паре: (логическая X, пиксельная X).
                    # Логическая понадобится для расчёта глубины,
                    # пиксельная — для заливки и отрисовки
                    xs.append((x_int, x_px))
            if xs:
                # Сортируем по X слева направо — чтобы потом легко объединять в пары L/R
                xs.sort(key=lambda it: it[0])
                per_poly_xs[pid] = xs

        # 3) Формируем пары «левое ребро — правое ребро» 
        # Проходим по каждому полигону, у которого есть пересечения со строкой
        for pid, xs in per_poly_xs.items():
            # Идём по списку пересечений с шагом 2: (0,1), (2,3), (4,5), ...
            for i in range(0, len(xs) - 1, 2):
                xL_log, xL_px = xs[i] # левая граница пары (логическая и пиксельная X)
                xR_log, xR_px = xs[i + 1] # правая граница пары
                # Считаем глубину полигона в точках пересечения
                zL = self.z_at(pid, xL_log, y_log)
                zR = self.z_at(pid, xR_log, y_log)
                # Сохраняем пару целиком — по ней будем заливать пиксели.
                # Формат: (лог.X левый, лог.X правый, пикс.X левый, пикс.X правый,
                # id полигона, глубина слева, глубина справа)
                self.active_pairs.append((xL_log, xR_log, xL_px, xR_px, pid, zL, zR))
                # Для панели «Активные рёбра (AEL)» — отдельно левое и правое ребро.
                # side = 'L' или 'R' — сторона ребра,
                # x_log, x_px, z — координаты и глубина в этой точке
                self.active_edges.append({'pid': pid, 'side': 'L',
                                          'x_log': xL_log, 'x_px': xL_px, 'z': zL})
                self.active_edges.append({'pid': pid, 'side': 'R',
                                          'x_log': xR_log, 'x_px': xR_px, 'z': zR})
                # Для визуализации: точки пересечения на экране.
                # Пиксельную X округляем до целого — чтобы рисовать кружок в пиксельной сетке
                self.current_intersections.append((pid, xL_log, int(round(xL_px))))
                self.current_intersections.append((pid, xR_log, int(round(xR_px))))
                # Отмечаем, что этот полигон активен на текущей строке
                self.active_polygons.add(pid)

        # Сортируем оба списка по X слева направо. Нужно для визуализации 
        self.current_intersections.sort(key=lambda it: it[1])
        self.active_edges.sort(key=lambda e: e['x_log'])

        # 4) Заполняем пикселы по правилу z-буфера 
        # Для каждой пары L/R перебираем пикселы между границами
        # и решаем, виден ли полигон в каждом из них
        for (xL_log, xR_log, xL_px, xR_px, pid, zL, zR) in self.active_pairs:
            # Округляем дробные пиксельные границы до целых номеров пикселов.
            # ceil (округление вверх) для левой — берём первый пиксел, попавший в пару.
            # floor (округление вниз) для правой — последний пиксел внутри пары
            xL_px_int = max(0, int(math.ceil(xL_px))) # не меньше 0
            xR_px_int = min(self.W - 1, int(math.floor(xR_px))) # не больше W-1

            # Если после обрезки интервал пустой — пропускаем пару
            if xR_px_int < xL_px_int:
                continue
            # Перебираем все пикселы внутри пары
            for px in range(xL_px_int, xR_px_int + 1):
                # Логическая X центра пиксела (пиксел = квадратик,
                # берём его центр, отсюда + 0.5)
                x_log = ((px + 0.5) - self.cx) / self.scale_screen # Переводим номер пиксела px обратно в логическую координату X
                # Считаем глубину полигона в этой точке через уравнение плоскости
                z = self.z_at(pid, x_log, y_log)
                if z is None: # глубину посчитать не удалось — пропускаем пиксел
                    continue
                # Главное правило z-буфера:
                # если новый полигон ближе того, что уже записано в этом пикселе,
                # он его перекрывает
                if z < self.scanline_zbuffer[px]: 
                    self.scanline_zbuffer[px] = z # обновляем z-буфер строки
                    self.scanline_fbuffer[px] = pid # буфер id полигона
                    self.frame_z[y_px, px] = z # итоговый z-буфер 
                    self.frame_pid[y_px, px] = pid # итоговый буфер id 

    # Возвращает копию z буфера, id буфера и списка активных ребер
    def get_zbuffer_row(self):
        return self.scanline_zbuffer.copy()

    def get_fbuffer_row(self):
        return self.scanline_fbuffer.copy()

    def get_active_edges_info(self):
        return list(self.active_edges)


# Виджет Qt
class GLWidget(QtWidgets.QWidget):
    def __init__(self, scene=None, parent=None):
        super().__init__(parent)
        # Минимальный размер окна 
        self.setMinimumSize(CANVAS_W, CANVAS_H)
        # Разрешаем виджету получать фокус клавиатуры (чтобы работали нажатия клавиш)
        self.setFocusPolicy(QtCore.Qt.StrongFocus)
        # Сцена: либо переданная снаружи, либо демо-сцена по умолчанию
        self.scene = scene if scene is not None else generate_demo_scene()
        # Положение камеры в мировых координатах.
        # Стоит на оси Z=15 и смотрит в начало координат
        self.camera_pos = np.array([0.0, 0.0, 15.0], dtype=float)
        # Точка, куда смотрит камера — центр сцены
        self.camera_target = np.array([0.0, 0.0, 0.0], dtype=float)
        # Вектор "вверх" — обычно (0, 1, 0), ось Y вверх
        self.camera_up = np.array([0.0, 1.0, 0.0], dtype=float)
        # Фокусное расстояние камеры для перспективной проекции
        self.focal = 4.0
        # Начальные размеры — берём максимум из текущих и констант
        w0 = max(self.width(), CANVAS_W)
        h0 = max(self.height(), CANVAS_H)
        # Масштаб
        self.scale_screen = min(w0, h0) * 0.5
        # Создаём ZBufferScanline с текущими параметрами
        self.algorithm = ZBufferScanline(
            self.scene, self.focal, w0, h0,
            self.scale_screen, self.camera_pos, self.camera_target, self.camera_up)
        # updated — перерисовать окно
        # rowCompleted — скопировать готовую строку в итоговое изображение
        self.algorithm.updated.connect(self.update)
        self.algorithm.rowCompleted.connect(self.on_engine_row_completed)

        # Карандаши (QPen) для рисования:
        # контур полигонов и три оси — X (красная), Y (зелёная), Z (синяя)
        self.poly_pen = QtGui.QPen(QtGui.QColor(40, 40, 160), 1)
        self.axis_pen_x = QtGui.QPen(QtGui.QColor(200, 40, 40), 2)
        self.axis_pen_y = QtGui.QPen(QtGui.QColor(40, 160, 40), 2)
        self.axis_pen_z = QtGui.QPen(QtGui.QColor(30, 90, 200), 2)
        
        # Пересчитываем сферические координаты камеры
        self._recalc_camera_spherical()
        # Переменные для обработки мыши
        self.last_mouse = None # последняя позиция курсора
        self.mouse_mode = None # текущий режим: 'orbit_cam' или None

        # Qt-изображение, куда построчно накапливается результат
        self.frame_image = None
        self._init_frame_image()
        # Показывать ли оси X/Y/Z на экране
        self.show_axes = True

        # Флаг, что идёт пошаговый режим (S)
        self.step_mode = False

    # Создаёт чистый QImage размером с виджет и заливает фоном
    def _init_frame_image(self):
        w, h = max(1, self.width()), max(1, self.height())
        self.frame_image = QtGui.QImage(w, h, QtGui.QImage.Format_ARGB32)
        self.frame_image.fill(QtGui.QColor(245, 245, 245).rgba())

    # Переводит положение камеры в сферические координаты:
    # радиус (расстояние до цели), азимут (угол в горизонтали),
    # угол места (угол над горизонтом). Нужно для вращения камеры мышью
    def _recalc_camera_spherical(self):
        v = self.camera_pos - self.camera_target
        r = np.linalg.norm(v)
        if r < 1e-9:
            r = 1e-9; v = np.array([r, 0, 0], dtype=float)
        self.cam_radius = r
        self.cam_el = math.asin(v[1] / r)
        self.cam_az = math.atan2(v[2], v[0])

    # Проверяет, видно ли ребро полигона pid в экранной точке (sx, sy)
    # с учётом z-буфера. Используется при отрисовке контуров: скрытые
    # другим полигоном ребра не рисуются
    # Параметры:
    #   pid — id полигона, которому принадлежит ребро
    #   sx, sy — экранные (пиксельные) координаты точки на ребре

    # Возвращает:
    #   True  — точку ребра видно, её надо рисовать
    #   False — точка скрыта другим полигоном
    def _edge_sample_visible_by_depth(self, pid, sx, sy):
        # Если сцена ещё не создана — не можем проверить, считаем видимой
        if self.algorithm is None:
            return True
        # Берём ширину и высоту экрана 
        W = self.algorithm.W; H = self.algorithm.H
        # Переводим дробные экранные координаты в целые номера пикселов.
        # Округляем к ближайшему: + 0.5 и floor = обычное округление
        ix = int(math.floor(sx + 0.5)); iy = int(math.floor(sy + 0.5))

        # Если точка вышла за пределы экрана — обрабатываем особым образом:
        # пока алгоритм не завершён — считаем «видимой», чтобы рисовать
        # всё, что попадает в кадр, даже если какая-то строка ещё не обработана
        # если всё уже посчитано — наоборот, «скрытой», потому что за
        # пределами экрана рисовать нечего
        if not (0 <= ix < W and 0 <= iy < H):
            return (not self.algorithm.finished)
        # Если размеры буфера не совпадают с ожидаемыми (например,
        # окно изменили), не рискуем идти дальше — возвращаем результат
        if iy >= self.algorithm.frame_z.shape[0] or ix >= self.algorithm.frame_z.shape[1]:
            return (not self.algorithm.finished)
        
        # Если строка ещё не обработана алгоритмом (её номер >= текущей),
        # глубина для неё ещё не посчитана. Считаем точку видимой — иначе
        # при прогрессивной отрисовке верхние строки «пропадали» бы
        if (not self.algorithm.finished) and (iy >= self.algorithm.cur_scanline):
            return True
        # Переводим пиксельные координаты в логические.
        # Центр экрана в пикселях:
        cx, cy = self.width() / 2.0, self.height() / 2.0
        # X: сдвигаем на центр и делим на масштаб
        x_log = (ix + 0.5 - cx) / self.scale_screen
        # Y: сначала переворачиваем ось (на экране Y вниз, в логике вверх)
        y_log = (cy - (iy + 0.5)) / self.scale_screen
        # Считаем глубину самого ребра в этой точке по уравнению плоскости
        z_edge = self.algorithm.z_at(pid, x_log, y_log)
        # Если глубину посчитать нельзя (плоскость полигона вырождена)
        # пока алгоритм ещё работает — считаем ребро видимым,
        # когда алгоритм полностью завершён — считаем ребро скрытым
        if z_edge is None:
            return (not self.algorithm.finished)
        
        # Берём из итогового z-буфера глубину того полигона,
        # который сейчас записан в этом пикселе
        try:
            z_frame = float(self.algorithm.frame_z[iy, ix])
        # Если что-то пошло не так с индексами — считаем +бесконечность
        # (то есть в пикселе «ничего нет»)
        except Exception:
            z_frame = np.inf
        # Финальное сравнение: ребро видно, если его глубина меньше той,
        # что уже записана в z-буфере. Меньше = ближе к камере
        return z_edge < z_frame - 1e-12

    def paintEvent(self, event):
        qp = QtGui.QPainter(self)
        qp.setRenderHint(QtGui.QPainter.Antialiasing)
        qp.fillRect(self.rect(), QtGui.QColor(245, 245, 245))
        w, h = self.width(), self.height()
        self.scale_screen = min(w, h) * 0.5
        self.algorithm.scale_screen = self.scale_screen

        need_resize = (
            self.algorithm.W != w or self.algorithm.H != h
            or self.algorithm.frame_pid is None
            or self.algorithm.frame_pid.shape[0] != h
            or self.algorithm.frame_pid.shape[1] != w
        )
        if need_resize:
            self.algorithm.W = w
            self.algorithm.H = h
            self.algorithm._reallocate_buffers()
            self.algorithm.reset()
            self._init_frame_image()

        cx, cy = w / 2.0, h / 2.0

        final_polys_2d = []
        for p in self.scene:
            proj, _ = project_with_camera_and_depth(
                p['verts'], self.camera_pos, self.camera_target,
                self.camera_up, self.focal)
            poly2d = []
            for v in proj:
                if v is None:
                    poly2d.append(None)
                else:
                    x_log, y_log, z_cam = v
                    poly2d.append((cx + x_log * self.scale_screen,
                                   cy - y_log * self.scale_screen))
            final_polys_2d.append((p['id'], poly2d, p['color']))

        if self.frame_image is not None:
            qp.drawImage(0, 0, self.frame_image)

        if self.show_axes:
            axis_len = 1.2
            origin = np.array([0.0, 0.0, 0.0, 1.0])
            axes = [(origin, np.array([axis_len, 0.0, 0.0, 1.0])),
                    (origin, np.array([0.0, axis_len, 0.0, 1.0])),
                    (origin, np.array([0.0, 0.0, axis_len, 1.0]))]
            pts = np.array([p for pair in axes for p in pair], dtype=float)
            proj_axes, _ = project_with_camera_and_depth(
                pts, self.camera_pos, self.camera_target, self.camera_up, self.focal)
            for idx, pen in enumerate((self.axis_pen_x, self.axis_pen_y, self.axis_pen_z)):
                p0 = proj_axes[2 * idx]; p1 = proj_axes[2 * idx + 1]
                if p0 is None or p1 is None:
                    continue
                sx1 = cx + p0[0] * self.scale_screen; sy1 = cy - p0[1] * self.scale_screen
                sx2 = cx + p1[0] * self.scale_screen; sy2 = cy - p1[1] * self.scale_screen
                qp.setPen(pen)
                qp.drawLine(int(sx1), int(sy1), int(sx2), int(sy2))

        qp.setPen(self.poly_pen)
        if self.frame_image is not None:
            for pid, poly2d, color in final_polys_2d:
                n = len(poly2d)
                for i in range(n):
                    p1 = poly2d[i]; p2 = poly2d[(i + 1) % n]
                    if p1 is None or p2 is None:
                        continue
                    sx1, sy1 = p1; sx2, sy2 = p2
                    dx = sx2 - sx1; dy = sy2 - sy1
                    seg_len = math.hypot(dx, dy)
                    if seg_len < 1e-6:
                        continue
                    samples = max(1, int(math.ceil(seg_len)))
                    for k in range(samples + 1):
                        t = k / samples
                        mx = sx1 + dx * t; my = sy1 + dy * t
                        ix = int(math.floor(mx + 0.5)); iy = int(math.floor(my + 0.5))
                        if not (0 <= ix < self.frame_image.width() and 0 <= iy < self.frame_image.height()):
                            continue
                        if self._edge_sample_visible_by_depth(pid, mx, my):
                            qp.drawPoint(ix, iy)
        else:
            for pid, poly2d, color in final_polys_2d:
                n = len(poly2d)
                for i in range(n):
                    p1 = poly2d[i]; p2 = poly2d[(i + 1) % n]
                    if p1 is None or p2 is None:
                        continue
                    qp.drawLine(QtCore.QPointF(p1[0], p1[1]),
                                QtCore.QPointF(p2[0], p2[1]))

        # Визуализация состояния алгоритма (сканирующая строка + AEL).
        # Показываем в трёх случаях:
        #   - идёт прогрессивный режим (running)
        #   - алгоритм на паузе и ещё не завершён (paused)
        #   - пользователь делает шаг вручную клавишей S (step_mode)
        y_scan = self.algorithm.cur_scanline
        show_progress = (0 <= y_scan < h) and (
            self.algorithm.running
            or (self.algorithm.paused and not self.algorithm.finished)
            or self.step_mode
        )

        if show_progress:
            # 4.1) сканирующая строка
            qp.setPen(QtGui.QPen(QtGui.QColor(200, 20, 20), 1, QtCore.Qt.DashLine))
            qp.drawLine(0, y_scan, w, y_scan)

            # 4.2) активные интервалы (пары "левое-правое ребро")
            for (xL_log, xR_log, xL_px, xR_px, pid, zL, zR) in self.algorithm.active_pairs:
                rectL = max(0, int(math.ceil(xL_px)))
                rectR = min(w - 1, int(math.floor(xR_px)))
                if rectL > rectR:
                    continue
                color = None
                for p in self.scene:
                    if p['id'] == pid:
                        color = p['color']; break
                if color is None:
                    continue
                c = QtGui.QColor(color); c.setAlpha(110)
                qp.setBrush(c)
                qp.setPen(QtGui.QPen(QtGui.QColor(80, 80, 80), 1))
                qp.drawRect(rectL, y_scan - 5, rectR - rectL + 1, 10)

            # 4.3) активные рёбра (пересечения) с подписями pid
            for (pid, x_log, x_px) in self.algorithm.current_intersections:
                qp.setBrush(QtGui.QColor(255, 255, 255))
                qp.setPen(QtGui.QPen(QtGui.QColor(0, 0, 0), 1))
                qp.drawEllipse(QtCore.QPointF(x_px, y_scan), 4, 4)
                qp.drawText(x_px + 6, y_scan - 6, f"P{pid}")

        # 4.4) Полоса z-буфера текущей строки
        self._draw_zbuffer_strip(qp, w, h)

        # 4.5) Строка состояния
        qp.setPen(QtGui.QPen(QtGui.QColor(10, 10, 10)))
        qp.setFont(QtGui.QFont("Consolas", 11))
        run_state = "Выполняется" if self.algorithm.running else (
            "Завершено" if self.algorithm.finished else "Остановлено")
        qp.drawText(10, 20,
                    f"Построчное сканирование с z-буфером — {run_state}    "
                    f"Строка: {self.algorithm.cur_scanline}/{self.height()}")
        n_act = len(self.algorithm.active_polygons)
        qp.drawText(10, 40, f"Активных полигонов: {n_act}    "
                             f"Активных рёбер: {len(self.algorithm.active_edges)}")

    def _draw_zbuffer_strip(self, qp, w, h):
        strip_h = 60
        y0 = h - strip_h - 10
        qp.setBrush(QtGui.QBrush(QtGui.QColor(255, 255, 255, 230)))
        qp.setPen(QtGui.QPen(QtGui.QColor(120, 120, 120), 1))
        qp.drawRect(10, y0, w - 20, strip_h)

        qp.setPen(QtGui.QColor(60, 60, 60))
        qp.setFont(QtGui.QFont("Consolas", 9))
        qp.drawText(15, y0 + 14,
                    "z-буфер текущей строки (светлее = ближе, темнее = дальше)")

        # Берём копию z-буфера текущей строки — массив длиной W.
        # Для каждого пиксела строки там лежит глубина (число или +бесконечность для фона)
        zb = self.algorithm.get_zbuffer_row()
        if zb is None:
            return
        # Отбрасываем пикселы фона (+бесконечность)
        finite = zb[np.isfinite(zb)]
        # Если на строке вообще ничего не нарисовано — визуализировать нечего
        if finite.size == 0:
            return
        # Минимальная и максимальная глубина на строке — нужны,
        # чтобы нормировать значения в диапазон [0, 1]
        #   0 — самая близкая точка, 1 — самая далёкая
        zmin = float(finite.min()); zmax = float(finite.max())
        # Разброс глубин на строке
        zrange = max(1e-6, zmax - zmin)

        # Куда рисовать столбики
        inner_x0 = 15; inner_y0 = y0 + 22
        inner_w = w - 30; inner_h = strip_h - 30
        # Идём по пикселам строки слева направо
        for px in range(0, min(self.algorithm.W, inner_w)):
            # Глубина в этом пикселе строки
            z = zb[px]
             # Если тут ничего не нарисовано
             # это место останется белым 
            if not np.isfinite(z):
                continue
            # Превращаем глубину в число от 0 до 1:
            # если z = zmin -> t = 0 (самая близкая точка)
            # если z = zmax -> t = 1 (самая далёкая)
            # если z где-то между -> t между 0 и 1
            t = (z - zmin) / zrange
            shade = int(255 * (1.0 - t) * 0.85 + 30)
            color = QtGui.QColor(shade, shade, min(255, shade + 30))
            qp.fillRect(inner_x0 + px, inner_y0, 1, inner_h, color)

    def on_engine_row_completed(self, y):
        if self.frame_image is None:
            return
        img_w = self.frame_image.width()
        img_h = self.frame_image.height()
        arr_pid = self.algorithm.frame_pid
        if arr_pid is None:
            return
        if y < 0 or y >= img_h or y >= arr_pid.shape[0]:
            return

        pid_to_rgba = {}
        for p in self.scene:
            c = p['color']
            pid_to_rgba[p['id']] = QtGui.qRgba(c.red(), c.green(), c.blue(), 255)
        bg = QtGui.QColor(245, 245, 245).rgba()

        max_x = min(img_w, arr_pid.shape[1], self.algorithm.W)
        for x in range(max_x):
            pid = int(arr_pid[y, x])
            if pid >= 0:
                self.frame_image.setPixel(x, y, pid_to_rgba.get(pid, bg))
            else:
                self.frame_image.setPixel(x, y, bg)

        if self.algorithm.running:
            self.update(0, y, max_x, 2)
            
    #  Управление мышью / клавиатурой
    def mousePressEvent(self, ev):
        if self.algorithm.running:
            return
        if ev.button() == QtCore.Qt.LeftButton:
            self.show_axes = True
            self.step_mode = False
            if self.algorithm.finished:
                self.algorithm.finished = False
                self.algorithm.frame_pid.fill(-1)
                self.algorithm.frame_z.fill(np.inf)
                self._init_frame_image()
            self.mouse_mode = "orbit_cam"
            v = self.camera_pos - self.camera_target
            r = np.linalg.norm(v)
            if r < 1e-9:
                r = 1e-9; v = np.array([r, 0, 0])
            self._orbit_start = (r, math.asin(v[1] / r), math.atan2(v[2], v[0]))
            self._orbit_start_mouse = ev.pos()
        self.last_mouse = ev.pos()

    def mouseMoveEvent(self, ev):
        if self.algorithm.running:
            return
        if self.last_mouse is None:
            return
        pos = ev.pos()
        if getattr(self, "mouse_mode", None) == "orbit_cam":
            start_r, start_el, start_az = self._orbit_start
            start_mouse = self._orbit_start_mouse
            ddx = pos.x() - start_mouse.x(); ddy = pos.y() - start_mouse.y()
            az = start_az + ddx * 0.01
            el = start_el + ddy * 0.01
            max_el = math.radians(89.0)
            el = max(-max_el, min(max_el, el))
            r = start_r
            x = r * math.cos(el) * math.cos(az)
            y = r * math.sin(el)
            z = r * math.cos(el) * math.sin(az)
            self.camera_pos = np.array([x, y, z], dtype=float) + self.camera_target
            self.algorithm.reset()
            self._init_frame_image()
            self.show_axes = True
            self.step_mode = False
            self.algorithm.set_camera(self.camera_pos)
            self._recalc_camera_spherical()
            self.update()
        self.last_mouse = pos

    def mouseReleaseEvent(self, ev):
        self.mouse_mode = None
        self.last_mouse = None

    def keyPressEvent(self, ev):
        k = ev.key()
        if k == QtCore.Qt.Key_R:
            self.reset_algorithm()
        elif k == QtCore.Qt.Key_Space:
            self.start_instant()
        elif k == QtCore.Qt.Key_S:
            if not self.algorithm.running:
                if self.algorithm.finished:
                    self.reset_algorithm()
                # Включаем пошаговый режим — как при прогрессивном запуске
                self.show_axes = False
                self.step_mode = True
                self.algorithm.on_tick()
                # Помечаем, что мы находимся в «паузе», чтобы визуализация
                # сканирующей строки и AEL отображалась
                if not self.algorithm.finished:
                    self.algorithm.paused = True
        self.update()

    def reset_algorithm(self):
        self.step_mode = False
        self.algorithm.reset()
        self._init_frame_image()
        self.show_axes = True
        self.update()

    def start_progressive(self):
        if self.algorithm.finished:
            self.reset_algorithm()
        self.step_mode = False
        self.show_axes = False
        self.algorithm.start()
        self.update()

    def stop_progressive(self):
        self.algorithm.pause()
        self.update()

    def start_instant(self):
        if self.algorithm.finished:
            self.reset_algorithm()
        self.step_mode = False
        self.setUpdatesEnabled(False)
        try:
            self._init_frame_image()
            self.show_axes = False
            self.algorithm.run_full()
        finally:
            self.setUpdatesEnabled(True)
            self.update()

