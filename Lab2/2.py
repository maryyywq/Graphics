# Строим матрицу вида (мировые -> камера)
def look_at_matrix(camera_pos: np.ndarray, target: np.ndarray, up: np.ndarray) -> np.ndarray:
    # camera_pos: положение камеры в мировых координатах
    # target: точка, на которую смотрит камера
    # up: мировой вектор "вверх" (обычно (0, 1, 0))
    #
    # Алгоритм:
    # 1) zc = normalize(target - camera) — направление взгляда камеры
    # 2) xc = normalize(cross(zc, up)) — правая ось камеры
    # 3) yc = cross(xc, zc) — вектор "вверх" камеры (ортогонален к обоим)
    # 4) Формируем матрицу из базиса (xc, yc, zc) и переносим так,
    #    чтобы камера оказалась в начале координат
    # Возвращает матрицу 4x4

    C = np.array(camera_pos, dtype=float)
    T = np.array(target, dtype=float)
    UP = np.array(up, dtype=float)
    # Направление взгляда (от камеры к цели)
    zc = T - C
    zn = np.linalg.norm(zc) # норма вектора (его длина)
    # Нормируем вектор, чтобы получить единичное направление.
    # Если камера совпала с целью (длина ~ 0), берём направление по умолчанию
    zc = zc / zn if zn > 1e-9 else np.array([0.0, 0.0, 1.0])
    xc = np.cross(zc, UP) # Правая ось камеры = векторное произведение Zc и UP
    xn = np.linalg.norm(xc)
    # Нормируем. Если UP коллинеарен Zc (камера смотрит ровно вверх/вниз),
    # векторное произведение даст ноль — берём ось X по умолчанию
    xc = xc / xn if xn > 1e-9 else np.array([1.0, 0.0, 0.0])
    # Восстанавливаем "истинный" вектор вверх камеры: он перпендикулярен
    # и Xc, и Zc, и уже единичной длины (так как Xc и Zc единичные)
    yc = np.cross(xc, zc)
    # Собираем матрицу вида 4x4
    V = np.eye(4, dtype=float)
    # Первые три строки — базисные векторы камеры
    V[0, 0:3] = xc; V[1, 0:3] = yc; V[2, 0:3] = zc
    # R = V[0:3, 0:3] — поворотная часть 3x3
    # t = -R @ C — перенос, чтобы камера оказалась в начале координат
    V[0:3, 3] = -V[0:3, 0:3] @ C # Результат (вектор из 3 элементов) записываем в четвёртый столбец первых трёх строк
    return V

# Проецирует 3D-точки (в мировых координатах) на плоскость экрана.
# Дополнительно возвращает глубину каждой точки (в системе камеры) — она понадобится алгоритму z-буфера
def project_with_camera_and_depth(pts4, camera_pos, target, up, focal):
    # pts4 – массив вершин в однородных координатах (x, y, z, 1)
    # camera_pos, target, up – параметры камеры
    # focal – фокусное расстояние для перспективной проекции

    # Возвращает кортеж (res, pts_cam):
    # 1) res – массив из N элементов, каждый либо None (точка позади камеры),
    # либо кортеж (x_log, y_log, z_cam): логические координаты + глубина
    # 2) pts_cam – все точки в системе координат камеры (массив N x 4),
    # нужны для построения уравнения плоскости полигона

    # Преобразуем точки в массив float
    pts = np.array(pts4, dtype=float)
     # Получаем матрицу вида (мировые -> камера)
    V = look_at_matrix(np.array(camera_pos, dtype=float),
                       np.array(target, dtype=float),
                       np.array(up, dtype=float))
    # Умножаем все точки на матрицу вида
    pts_cam = (V @ pts.T).T
    res = []
    eps = 1e-9
    for p in pts_cam:
        x, y, z, w = p  # извлекаем координаты точки 
        if z <= eps: # Если точка на плоскости камеры или позади неё (z <= 0)
            res.append(None); continue # перспективная проекция не определена — помечаем None
        # Коэффициент перспективы: чем дальше точка (больше z),
        # тем меньше t, тем сильнее точка "сжимается" к центру экрана
        t = focal / z
        # Логические координаты проекции: x_log = x * f / z, y_log = y * f / z.
        # Глубину z тоже сохраняем — она нужна алгоритму z-буфера,
        # чтобы понимать, какой полигон ближе к камере
        res.append((x * t, y * t, z))
        # np.array(..., dtype=object) — потому что элементы разнородные:
        # либо кортеж из трёх чисел, либо None. Обычный числовой dtype не подойдёт
    return np.array(res, dtype=object), pts_cam

# Создаёт случайный многоугольник в 3D-пространстве
# (лежащий в плоскости, которую задаём центром и нормалью)
def make_polygon(center, normal, radius, n_verts):
    # center   – центр многоугольника в мировых координатах
    # normal   – вектор нормали к плоскости, в которой лежит многоугольник
    # radius   – радиус окружности, в которую вписывается многоугольник
    # n_verts  – количество вершин (3–6)

    # Возвращает список вершин в однородных координатах (x, y, z, 1)

    # Приводим нормаль к массиву float и сразу нормируем (делаем длиной 1).
    # 1e-12 добавлен, чтобы не делить на ноль, если вектор нулевой
    n = np.array(normal, dtype=float); n /= (np.linalg.norm(n) + 1e-12)
    # Нам нужны два перпендикулярных вектора u и v, лежащих в плоскости
    # многоугольника. Они будут локальными осями внутри плоскости.
    # Чтобы получить первый из них, берём любой вектор a, не параллельный n
    a = np.array([1.0, 0.0, 0.0]) if abs(n[0]) < 0.9 else np.array([0.0, 1.0, 0.0])
    # u = нормаль * a. Получается вектор, перпендикулярный и n, и a,
    # значит лежит в плоскости многоугольника. Нормируем
    u = np.cross(n, a); u /= (np.linalg.norm(u) + 1e-12)
    # v = нормаль * u. Второй вектор внутри плоскости, перпендикулярный u.
    # Вместе u и v образуют базис плоскости многоугольника
    v = np.cross(n, u); v /= (np.linalg.norm(v) + 1e-12)
    # Генерируем n_verts случайных углов от 0 до 2π и сразу сортируем их
    # по возрастанию. Это нужно, чтобы вершины многоугольника шли друг за
    # другом по кругу, а не в случайном порядке
    angles = sorted([random.random() * 2 * math.pi for _ in range(n_verts)])
    verts = []
    for ang in angles:
        # Случайный радиус (от 60% до 100% от заданного)
        r = radius * (0.6 + 0.4 * random.random())
        # Точка на плоскости: центр + смещение по осям u и v.
        # cos(ang)*u + sin(ang)*v — это радиус-вектор в плоскости многоугольника
        p = np.array(center) + r * (math.cos(ang) * u + math.sin(ang) * v)
        # Сохраняем как однородные координаты (x, y, z, 1)
        verts.append((p[0], p[1], p[2], 1.0))
    return verts


